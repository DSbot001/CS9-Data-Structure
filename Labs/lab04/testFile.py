from Stack import Stack
from lab04 import solveMaze

def test_stack():
    s = Stack()
    assert s.isEmpty() == True

    s.push([4, 4])
    s.push([3, 4])

    assert s.size() == 2
    assert s.peek() == [3, 4]
    assert s.size() == 2       

    assert s.pop() == [3, 4]
    assert s.peek() == [4, 4]

    assert s.pop() == [4, 4]
    assert s.isEmpty() == True



def test_example():
    maze = [
        ['+', '+', '+', '+', 'G', '+'],
        ['+', ' ', '+', ' ', ' ', '+'],
        ['+', ' ', ' ', ' ', '+', '+'],
        ['+', ' ', '+', '+', ' ', '+'],
        ['+', ' ', ' ', ' ', ' ', '+'],
        ['+', '+', '+', '+', '+', '+']
    ]

    assert solveMaze(maze, 4, 4) == True

    assert maze == [
        ['+', '+', '+', '+', 'G', '+'],
        ['+', 8, '+', 11, 12, '+'],
        ['+', 7, 9, 10, '+', '+'],
        ['+', 6, '+', '+', 2, '+'],
        ['+', 5, 4, 3, 1, '+'],
        ['+', '+', '+', '+', '+', '+']
    ]



